ROOT_OUTRO = """
## A note on the lung cancer work

The lung cancer projects study **data leakage in slice-level medical image splits**.
The IQ-OTH/NCCD dataset ships no patient identifier, so the honest comparison here is
between a random shuffle of slices and a split that respects file order. It is an
**ordering split**, not a patient-level split, and the difference matters: with a
random shuffle, slices from the same scan land on both sides of the split and the
reported accuracy is inflated. Holding the split ratio and the architecture fixed
across three seeds, moving from the shuffled split to the ordered split costs about
**7.5 percentage points** of accuracy.

Earlier write-ups of this work described the ordered condition as patient-level and
quoted a larger gap. That was wrong on both counts, and the numbers above supersede it.

## Reproducing

The training code targets Kaggle paths (`/kaggle/input/...`) and Kaggle accelerators.
To rerun a project, upload its `code/` directory as a Kaggle notebook and attach the
dataset named in the notebook header.

## Contact

Tahmidul Bin Ferdous, C221065, turing.accessories@gmail.com
"""


def main():
    by_project = load_runs()
    meta = load_projects()
    PROJECTS.mkdir(parents=True, exist_ok=True)

    summary, total_runs = [], 0
    for project, m in sorted(meta.items(), key=lambda kv: kv[1]["createdAt"], reverse=True):
        runs = by_project.get(project, [])
        if not runs:
            continue
        d = PROJECTS / project
        d.mkdir(parents=True, exist_ok=True)
        ncfg, nmet = write_runs_csv(d / "runs.csv", runs)
        nfig = copy_figures(project, runs, d / "figures")
        (d / "README.md").write_text(project_readme(project, m, runs, ncfg, nmet, nfig))
        for sub, note in (("code", "Training code for this project goes here."),
                          ("weights", "Final checkpoint for this project goes here.")):
            p = d / sub
            p.mkdir(exist_ok=True)
            if not any(p.iterdir()):
                (p / "README.md").write_text(f"# {sub}\n\n{note}\n")
        total_runs += len(runs)
        summary.append((project, m, len(runs), nfig))
        print(f"{project:32s} {len(runs):3d} runs  {nfig:3d} figures")

    dates = sorted(r["created_at"][:7] for rs in by_project.values() for r in rs)
    body = [ROOT_INTRO.format(nruns=total_runs, nproj=len(summary),
                              first=dates[0], last=dates[-1])]
    body.append("| Project | Runs | Period | What it is |")
    body.append("| --- | --- | --- | --- |")
    for project, m, n, _ in summary:
        period = f"{m['createdAt'][:7]} to {(m['lastActive'] or m['updatedAt'])[:7]}"
        body.append(f"| [{project}](projects/{project}/) | {n} | {period} | "
                    f"{DESCRIPTIONS.get(project, '')} |")
    body.append(ROOT_OUTRO)
    (ROOT / "README.md").write_text("\n".join(body))
    print(f"\n{total_runs} runs across {len(summary)} projects -> {ROOT}")


